"""Export the human-walk policy for C++: the frozen actor, the reference motion, the robot's
constants, the launch profile.

Needs the training checkout (humanoid-full/policies: motion.py and policy-walk-human with its
plan and checkpoints).  Nothing is retrained and no weight or normalizer is changed.

  python -m unitree_human_walk.export [--training-root ../humanoid-full/policies] [--output <new directory>]
"""
import argparse
import json
import shutil
import struct
from pathlib import Path

from unitree_parametrized_skills.export import contract, digest, fnv, kinematics

from . import CHECKPOINT, FRAME, MAGIC, MOTION, MOTOR_IDS, OBSERVATION, PACKAGE, PROFILE, REFERENCE, ROOT, TERMS, TRAINING
from .estimate import Estimate
from .training import modules

SOURCES = ('motion.py', 'task.py', 'scene.py', 'g1_23dof.py', f'{MOTION}/plans.py', f'{MOTION}/README.md')
WALK = ROOT / 'deploy/robots/g1_23dof/config/policy/parametrized_walk/v2/params/estimator.json'


def actor(path, hidden):
    """The checkpoint's actor: observations (1, 145) -> the correction on the joints (1, 23), normalizer included."""
    import torch
    from rsl_rl.models import MLPModel
    from tensordict import TensorDict
    state = torch.load(path, map_location='cpu', weights_only=False)
    model = MLPModel(TensorDict({'actor': torch.zeros(1, OBSERVATION)}, batch_size=[1]), {'actor': ['actor']}, 'actor', 23,
                     hidden_dims=hidden, activation='elu', obs_normalization=True,
                     distribution_cfg={'class_name': 'GaussianDistribution', 'init_std': .3, 'std_type': 'scalar'}).eval()
    model.load_state_dict(state['actor_state_dict'], strict=True)

    class Inference(torch.nn.Module):
        def __init__(self):
            super().__init__()
            self.norm, self.mlp = model.obs_normalizer, model.mlp

        def forward(self, observations):
            return self.mlp(self.norm(observations))
    return Inference().eval(), int(state['iter'])


def reference(bank, joints):
    """The plan's frames (T, 78) in the robot's joint order, and what the bank says about it."""
    import numpy as np
    import torch
    b = torch.load(bank, map_location='cpu', weights_only=False)
    perm = [b['joint_names'].index(n) for n in joints]
    p = {k: v[0].numpy() for k, v in b['plan'].items() if k != 'len'}
    length = int(b['plan']['len'][0])
    torso = p['body'][:length, b['body_names'].index('torso_link')]
    frames = np.concatenate((p['qcmd'][:length][:, perm], p['qpos'][:length, 7:][:, perm], p['qvel'][:length, 6:][:, perm],
                             torso, p['qpos'][:length, :2]), -1).astype('<f4')
    assert frames.shape == (length, FRAME) and np.isfinite(frames).all() and b['fps'] == 50
    q0 = p['qpos'][0]
    # the plan starts under the pelvis, facing along x, upright, and at rest
    assert np.abs(q0[:2]).max() < 1e-6 and abs(q0[3] - 1) < 1e-3 and np.abs(p['qvel'][0]).max() < 1e-3
    return frames, {'title': b['title'], 'source': b.get('source'), 'phases': b['phases'], 'walk': b['walk'],
                    'stats': {k: v for k, v in b['stats'].items() if isinstance(v, (int, float, str, list))}}


def header(interface, frames, constants, hashes, seconds, metres):
    def array(name, values, kind='float'):
        def value(x):
            return f'{float(x):.10e}f' if kind == 'float' else str(x)
        return f'inline constexpr std::array<{kind},{len(values)}> {name}{{{{' + ','.join(map(value, values)) + '}};\n'
    h = ('// Generated by unitree_human_walk.export. Do not edit.\n'
         '#pragma once\n#include <array>\n#include <cstdint>\nnamespace human_walk {\n'
         'inline constexpr float kStepDt = .02f;\n'
         f'inline constexpr uint64_t kActorHash = {hashes[0]}ULL;\n'
         f'inline constexpr uint64_t kReferenceHash = {hashes[1]}ULL;\n'
         f'inline constexpr int kFrames = {len(frames)};\n'
         f'inline constexpr float kPlanSeconds = {seconds:.10e}f;\n'
         f'inline constexpr float kWalkMetres = {metres:.10e}f; // the plan\'s pelvis, start to end\n')
    h += array('kMotorIds', MOTOR_IDS, 'int')
    for name, key in (('kDefault', 'default_joint_positions'), ('kScale', 'action_scale'), ('kKp', 'kp'), ('kKd', 'kd')):
        h += array(name, interface[key])
    h += array('kStart', frames[0, 23:46].tolist()) + array('kEnd', frames[-1, 23:46].tolist())
    soles = constants['soles']
    assert len(soles) == 2 and len(soles[0]) == len(soles[1]) and len(soles[0]) % 3 == 0
    h += (f'// the ends of each sole\'s collision capsules at its underside, in the foot body\'s frame (x y z each)\n'
          f'inline constexpr int kSolePoints = {len(soles[0]) // 3};\n')
    h += array('kLeftSole', soles[0]) + array('kRightSole', soles[1])
    for name, key in (('kTorsoPosition', 'torso_position'), ('kTorsoRotation', 'torso_rotation'),
                      ('kWaistAxis', 'waist_axis'), ('kWaistAnchor', 'waist_anchor'), ('kImu', 'imu')):
        h += array(name, constants[key])
    h += f'inline constexpr int kWaist = {constants["waist_joint"]}; // the waist joint, in the joint order\n'
    return h + '}\n'


def write_profile(interface, start):
    """Passive, FixStand, Velocity and the walk; the box profiles' Passive/FixStand/Velocity."""
    import yaml
    cfg = yaml.safe_load((ROOT / 'deploy/robots/g1_23dof/config/box_three.yaml').read_text())
    old = cfg['FSM']
    passive = {'Passive': 'LT + B.on_pressed'}
    fsm = {'_': {'Passive': {'id': 1}, 'FixStand': {'id': 2}, 'Velocity': {'id': 3, 'type': 'RLBase'},
                 'HumanWalk': {'id': 4, 'type': 'HumanWalk'}}}
    for name in ('Passive', 'FixStand', 'Velocity'):
        fsm[name] = old[name]
    fsm['FixStand']['transitions'] = {**passive, 'Velocity': 'RB + X.on_pressed'}
    pose = [0.] * 29
    for field in ('kp', 'kd'):
        fsm['FixStand'][field] = [0.] * 29
        for i, motor in enumerate(MOTOR_IDS):
            fsm['FixStand'][field][motor] = interface[field][i]
    for i, motor in enumerate(MOTOR_IDS):
        pose[motor] = float(start[i])
    fsm['FixStand']['qs'] = [[], pose]
    fsm['Velocity']['transitions'] = {**passive, 'HumanWalk': 'RB + Y.on_pressed'}
    fsm['HumanWalk'] = {'transitions': {**passive, 'Velocity': 'RB + X.on_pressed'},
                        'policy_dir': str(PACKAGE.relative_to(ROOT / 'deploy/robots/g1_23dof')),
                        'blend_s': .5, 'hold_s': 1., 'odometry_scale': 1.,
                        # seconds after the reference ends at which Velocity takes over by itself (0: never).  Left
                        # standing, the walk policy fell in simulation on floors with friction 1.2 and more.
                        'return_s': .5}
    cfg['FSM'] = fsm
    PROFILE.write_text(yaml.safe_dump(cfg, sort_keys=False))


def export(root, output, checkpoint):
    import torch
    motion, tk = modules(root)
    root, output = Path(root).resolve(), Path(output).resolve()
    folder = root / MOTION
    cfg = motion.env_cfg(str(folder), num_envs=1, play=True)
    model, interface = contract(cfg)
    assert model.nu == 23 and interface['policy_dt'] == .02
    box = json.loads((ROOT / 'deploy/robots/g1_23dof/config/policy/box/v1/params/contract.json').read_text())
    for key in ('joint_order', 'action_order', 'action_scale', 'default_joint_positions', 'kp', 'kd'):
        if interface[key] != box[key]:
            raise ValueError(f'The human-walk robot differs from the box robot in {key}')
    assert tuple(motion.observations(lambda lo: None)) == tuple(n for n, _ in TERMS)
    agent = motion.ppo_cfg(str(folder))
    hidden = tuple(agent.actor.hidden_dims)

    # training compensates the arms' gravity; the robot does it with the arm motors (the box-three controller's torque)
    arms = [i for i in range(model.nbody) if model.body_gravcomp[i]]
    assert all(any(k in model.body(i).name for k in ('shoulder', 'elbow', 'wrist')) for i in arms) and len(arms) == 10
    assert all(model.body_gravcomp[i] == 1 for i in arms)
    interface['arm_gravity_compensation'] = {
        'bodies': [model.body(i).name for i in arms],
        'in_training': 'MuJoCo body gravcomp: the arm joints through their motors, and the pelvis for free',
        'on_the_robot': 'feedforward torque on the ten arm motors (table_box::gravity_torque)'}

    # the pelvis estimator is the walk controller's: same legs, same filter
    walk = json.loads(WALK.read_text())
    from unitree_parametrized_skills.reference import odometry
    feet = kinematics(odometry, model, interface['joint_order'])
    K = odometry.KalmanOdometry
    filt = {'kSoft': K.SOFT, 'kSigA': K.SIG_A, 'kSigB': K.SIG_B, 'kSigV': K.SIG_V, 'kGate': K.GATE,
            'kP0Position': K.P0[0], 'kP0Velocity': K.P0[1], 'kP0Bias': K.P0[2]}
    if json.dumps(feet) != json.dumps(walk['feet']) or filt != walk['constants']:
        raise ValueError('The leg kinematics or filter constants differ from the parametrized-walk package the controller reuses')
    constants = Estimate(model, interface['joint_order'], 1, 'cpu').constants()

    output.mkdir(parents=True, exist_ok=False)
    params = output / 'params'
    params.mkdir()
    shutil.copy2(folder / checkpoint, output / 'checkpoint.pt')
    module, iteration = actor(output / 'checkpoint.pt', hidden)
    with torch.inference_mode():
        torch.onnx.export(module, torch.zeros(1, OBSERVATION), str(output / 'policy.onnx'),
                          input_names=['observations'], output_names=['actions'], opset_version=18, dynamo=False)
    frames, plan = reference(folder / 'banks/plan.pt', interface['joint_order'])
    (output / 'reference.bin').write_bytes(MAGIC + struct.pack('<II', len(frames), FRAME) + frames.tobytes())
    seconds = (len(frames) - 1) * .02
    metres = float(frames[-1, 76] - frames[0, 76])
    info = {'motion': MOTION, 'checkpoint_source': str(folder / checkpoint), 'iteration': iteration,
            'checkpoint_sha256': digest(output / 'checkpoint.pt'), 'hidden': list(hidden), 'plan': plan,
            'trained_with_estimator': None,
            'trained_inputs': 'the simulator\'s torso pose and IMU velocity, with uniform noise (0.05 and 0.3 m/s)',
            'trained_randomization': 'foot friction 0.4-1.2, encoder bias 0.01 rad, pushes up to 0.4 m/s; nothing else'}
    (output / 'source_metadata.json').write_text(json.dumps(info, indent=2, default=str) + '\n')
    (params / 'contract.json').write_text(json.dumps(interface, indent=2) + '\n')
    (params / 'estimator.json').write_text(json.dumps({'filter': filt, 'feet': feet, **constants}, indent=2) + '\n')
    (params / 'PolicyConfig.h').write_text(header(interface, frames, constants,
                                                  (fnv(output / 'policy.onnx'), fnv(output / 'reference.bin')), seconds, metres))
    manifest = {'format': 'g1-human-walk-v1', 'hardware_validated': False, 'estimator': 'kalman leg odometry + sole height',
                'source_root': str(root), 'actor': {k: info[k] for k in info if k != 'plan'}, 'interface': interface,
                'reference': {'frames': len(frames), 'fps': 50, 'seconds': seconds, 'walk_m': metres, 'title': plan['title'],
                              'frame': ['qcmd/' + n for n in interface['joint_order']] + ['q/' + n for n in interface['joint_order']]
                              + ['dq/' + n for n in interface['joint_order']]
                              + ['torso_x', 'torso_y', 'torso_z', 'torso_qw', 'torso_qx', 'torso_qy', 'torso_qz', 'pelvis_x', 'pelvis_y']},
                'observation': [list(t) for t in TERMS]}
    manifest['actor']['onnx_sha256'] = digest(output / 'policy.onnx')
    if output == PACKAGE.resolve():
        write_profile(interface, frames[0, 23:46])
        REFERENCE.mkdir(exist_ok=True)      # the training source the C++ port follows, for the record
        for name in SOURCES:
            shutil.copy2(root / name, REFERENCE / Path(name).name)
        manifest['source_files'] = {Path(name).name: digest(REFERENCE / Path(name).name) for name in SOURCES}
    manifest['files'] = {str(p.relative_to(output)): digest(p) for p in sorted(output.rglob('*')) if p.is_file()}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(output, f'{len(frames)} frames ({seconds:.2f} s), {metres:.3f} m, iteration {iteration}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--training-root', type=Path, default=TRAINING)
    parser.add_argument('--output', type=Path, default=PACKAGE)
    parser.add_argument('--checkpoint', default=CHECKPOINT)
    args = parser.parse_args()
    export(args.training_root, args.output, args.checkpoint)
